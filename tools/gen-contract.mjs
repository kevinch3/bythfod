#!/usr/bin/env node
/**
 * Generates TypeScript types from the VENDORED contract (contract/openapi.yaml),
 * not from eistedglobal directly — this repo must build without that one
 * checked out. Refresh the vendored copy with `npm run contract:sync` first.
 *
 *   node tools/gen-contract.mjs [--check]
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const spec = join(root, 'contract/openapi.yaml');
const out = join(root, 'src/contract/api.generated.ts');
const check = process.argv.includes('--check');

const hash = createHash('sha256').update(readFileSync(spec)).digest('hex').slice(0, 16);
const raw = execFileSync('npx', ['openapi-typescript', spec, '--empty-objects-unknown'],
  { cwd: root, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 });

// Types only: a value export here would be shipped code, and the API layer is
// excluded from the public build precisely so none of it reaches the browser.
const valueExport = raw.match(/^export\s+(?!type\b|interface\b)(\w+)/m);
if (valueExport) {
  console.error(`✘ generated output contains a value export (${valueExport[1]})`);
  process.exit(1);
}

const content = `/**
 * GENERATED by \`npm run contract:gen\` — do not edit.
 * Source: contract/openapi.yaml (sha256 ${hash}), vendored from eistedglobal.
 */
${raw}`;

if (check) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== content) {
    console.error('✘ src/contract/api.generated.ts is stale — run `npm run contract:gen`');
    process.exit(1);
  }
  console.log('✔ contract types up to date');
} else {
  writeFileSync(out, content);
  console.log(`✔ wrote src/contract/api.generated.ts (spec ${hash})`);
}
